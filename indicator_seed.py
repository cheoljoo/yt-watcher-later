def seed(con):
    """기본 지표를 등록한다(없을 때만 생성). 설명은 이미 채워 두어 AI 설명·출처 매핑 단계가 건너뛴다."""
    now, n = D.now(), 0
    for s in SEED:
        row = con.execute("SELECT id, source, description FROM indicators WHERE name=?", (s["name"],)).fetchone()
        if not row:
            con.execute("""INSERT INTO indicators(name,category,unit,description,interpretation,baseline,importance,warn_low,warn_high,enriched_at,first_seen_at,
                           active,source,symbol,mapped_at) VALUES(?,?,?,?,?,?,?,?,?,?,?,1,?,?,?)""",
                        (s["name"], s["category"], s["unit"], s["description"], s["interpretation"], s["baseline"], s["importance"], s["warn_low"], s["warn_high"],
                         now, now, s["source"], s["symbol"], now)); n += 1
        elif s["source"] != "none" and (row["source"] in (None, "none")):
            con.execute("UPDATE indicators SET source=?, symbol=?, mapped_at=? WHERE id=?", (s["source"], s["symbol"], now, row["id"]))
            if (row["description"] or "").startswith("※ 자동 수집 미연결"):          # 예전 '미연결' 설명이면 새 설명으로 교체
                con.execute("UPDATE indicators SET description=?, interpretation=?, baseline=?, importance=? WHERE id=?",
                            (s["description"], s["interpretation"], s["baseline"], s["importance"], row["id"]))
    for name in RETIRED: con.execute("UPDATE indicators SET active=0 WHERE name=? AND (source IS NULL OR source='none')", (name,))
    con.commit()
    return n
